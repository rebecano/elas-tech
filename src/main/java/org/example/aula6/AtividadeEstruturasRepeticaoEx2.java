package org.example.aula6;

// 2 - Mostre a contagem regressiva de 10 até 1 e depois a palavra "Fim!".

public class AtividadeEstruturasRepeticaoEx2 {
    static void main() {
        for (int i = 10; i >= 1; i--){
            System.out.println(i);
        }
        System.out.println("Fim!");
    }
}
